function detectInstallerLanguage(rawLocale) {
  const lower = String(rawLocale || "").toLowerCase();
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("zh")) return "zh";
  if (lower.startsWith("ko")) return "ko";
  if (lower.startsWith("en")) return "en";
  return "en";
}

function translateInstaller(lang, key, vars) {
  const dict = INSTALLER_TRANSLATIONS[lang] || INSTALLER_TRANSLATIONS.en;
  let text = dict[key];
  if (text === undefined) {
    text = INSTALLER_TRANSLATIONS.en[key] ?? key;
  }
  if (vars && typeof text === "string") {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return text;
}

